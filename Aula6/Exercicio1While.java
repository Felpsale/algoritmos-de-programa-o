//Escreva um algoritmo que imprima a sequência do número 100 ao 200

package Aula6;


public class Exercicio1While {
    public static void main(String[] args) {
        
    int cont = 100;

    while (cont <= 200 ) {

    System.out.println(cont);
    cont ++;
        
    }

    }
    
}
